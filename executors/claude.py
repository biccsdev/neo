"""Claude Code executor: explicit-UUID sessions and exact-ID resumes.

The session id is generated by NEO, passed with ``--session-id``, and then
required to come back unchanged. A stream that reports a different id is a
copy, not a continuation, and is rejected. Resumes use ``--resume <exact-id>``
with no ``--fork-session`` and never ``--continue``.
"""

from __future__ import annotations

import uuid
from typing import List, Optional

from executors.base import (
    STATUS_COMPLETED,
    STATUS_FAILED,
    STATUS_NEEDS_APPROVAL,
    STATUS_NEEDS_INPUT,
    ExecutorAdapter,
    ExecutorConfigError,
    ExecutorResult,
    FollowUpNotSupportedError,
    StreamCollector,
    check_line_source,
    clip,
    validate_argv,
    validate_exit_code,
    validate_prompt,
    validate_workdir,
)

_OUTPUT_FLAGS = ["--output-format", "stream-json", "--verbose"]
_QUESTION_TOOLS = frozenset({"askuserquestion"})


def validate_uuid(value, *, label: str = "session id") -> str:
    """Return the canonical UUID string, refusing anything else."""

    if isinstance(value, uuid.UUID):
        return str(value)
    if not isinstance(value, str) or not value:
        raise ExecutorConfigError("%s must be a UUID string" % label)
    if value != value.strip() or value.startswith("-"):
        raise ExecutorConfigError("%s is not a UUID: %r" % (label, value))
    try:
        return str(uuid.UUID(value))
    except (ValueError, AttributeError, TypeError):
        raise ExecutorConfigError("%s is not a UUID: %r" % (label, value)) from None


class ClaudeExecutor(ExecutorAdapter):
    """Build and interpret ``claude -p --output-format stream-json``."""

    name = "claude"

    def __init__(self, binary: str = "claude", *, uuid_factory=None) -> None:
        if not isinstance(binary, str) or not binary:
            raise ExecutorConfigError("claude binary must be a non-empty string")
        self.binary = binary
        self._uuid_factory = uuid_factory or uuid.uuid4

    # -- argv -----------------------------------------------------------

    def new_session_id(self) -> str:
        """Generate the explicit UUID that the CLI must echo back."""

        return validate_uuid(self._uuid_factory(), label="generated session id")

    def build_initial_argv(
        self,
        prompt,
        *,
        workdir: Optional[str] = None,
        session_id: Optional[str] = None,
    ) -> List[str]:
        prompt = validate_prompt(prompt)
        if workdir is not None:
            # Claude runs in the process working directory; an absolute workdir
            # is validated here so a caller never believes it was applied.
            validate_workdir(workdir)
        sid = validate_uuid(session_id) if session_id is not None else self.new_session_id()
        argv = [self.binary, "-p", "--session-id", sid] + _OUTPUT_FLAGS + ["--", prompt]
        return validate_argv(argv)

    def build_resume_argv(
        self, session_id, prompt, *, workdir: Optional[str] = None
    ) -> List[str]:
        sid = validate_uuid(session_id, label="session id")
        prompt = validate_prompt(prompt, label="follow-up")
        if workdir is not None:
            validate_workdir(workdir)
        argv = [self.binary, "-p", "--resume", sid] + _OUTPUT_FLAGS + ["--", prompt]
        return validate_argv(argv)

    def build_queue_argv(self, session_id, prompt) -> List[str]:
        raise FollowUpNotSupportedError(
            "Claude Code cannot queue into an active turn; wait for the turn to end "
            "and resume the exact session, because a replacement session is not "
            "an accepted continuation"
        )

    # -- parsing --------------------------------------------------------

    def parse_stream(
        self,
        lines,
        *,
        expected_session_id: Optional[str] = None,
        exit_code: int = 0,
    ) -> ExecutorResult:
        expected = (
            validate_uuid(expected_session_id, label="expected session id")
            if expected_session_id is not None
            else None
        )
        exit_code = validate_exit_code(exit_code)
        collector = StreamCollector()

        first_id: Optional[str] = None
        conflict: Optional[tuple] = None
        result_event: Optional[dict] = None
        assistant_text: Optional[str] = None
        assistant_error: Optional[str] = None
        needs_input: Optional[str] = None
        needs_approval: Optional[str] = None

        def note(source: str, raw) -> None:
            nonlocal first_id, conflict
            if raw is None:
                return
            if not isinstance(raw, str) or not raw.strip():
                collector.malformed.append(
                    "%s event without a usable session_id" % source
                )
                return
            # The CLI is allowed to echo an uppercase form; anything that is not
            # a UUID is a protocol violation, not a session handle.
            try:
                value = validate_uuid(raw.strip())
            except ExecutorConfigError:
                collector.malformed.append(
                    "%s event reported a non-UUID session_id: %r" % (source, raw)
                )
                return
            if first_id is None:
                first_id = value
            elif value != first_id and conflict is None:
                conflict = (first_id, value)

        for event in collector.read(check_line_source(lines)):
            kind = event.get("type")
            if not isinstance(kind, str) or not kind:
                collector.malformed.append("event without a string type")
                continue

            if kind == "system":
                subtype = event.get("subtype")
                if subtype == "init":
                    note("system/init", event.get("session_id"))
                elif subtype == "permission_denied":
                    needs_approval = (
                        "Claude reported a permission denial; approval is required."
                    )
            elif kind == "assistant":
                note("assistant", event.get("session_id"))
                message = event.get("message")
                if not isinstance(message, dict):
                    collector.malformed.append(
                        "assistant event without a message object"
                    )
                    continue
                content = message.get("content")
                if isinstance(content, str):
                    if content.strip():
                        assistant_text = content.strip()
                elif isinstance(content, list):
                    for block in content:
                        if not isinstance(block, dict):
                            continue
                        block_type = block.get("type")
                        if block_type == "text":
                            text = block.get("text")
                            if isinstance(text, str) and text.strip():
                                assistant_text = text.strip()
                        elif block_type == "tool_use":
                            name = block.get("name")
                            if (
                                isinstance(name, str)
                                and name.strip().lower() in _QUESTION_TOOLS
                            ):
                                needs_input = (
                                    "Claude asked a question and is waiting for an "
                                    "answer."
                                )
                error = event.get("error")
                if isinstance(error, str) and error.strip():
                    assistant_error = error.strip()
            elif kind == "result":
                result_event = event
                note("result", event.get("session_id"))
            elif kind == "user":
                note("user", event.get("session_id"))

        if collector.malformed:
            return self._result(
                STATUS_FAILED,
                session_id=first_id,
                final_message=assistant_text,
                collector=collector,
                error=collector.malformed[0],
                error_code="malformed_stream",
            )

        if conflict is not None:
            return self._result(
                STATUS_FAILED,
                session_id=first_id,
                final_message=assistant_text,
                collector=collector,
                error=(
                    "conflicting session ids reported: %s then %s; a copied or "
                    "replaced session cannot be resumed exactly" % conflict
                ),
                error_code="session_conflict",
            )

        if expected is not None and first_id is not None and first_id != expected:
            return self._result(
                STATUS_FAILED,
                session_id=first_id,
                final_message=assistant_text,
                collector=collector,
                error=(
                    "returned session id %s does not equal expected session id %s"
                    % (first_id, expected)
                ),
                error_code="session_mismatch",
            )

        if needs_input is not None:
            return self._result(
                STATUS_NEEDS_INPUT,
                session_id=first_id,
                final_message=assistant_text,
                collector=collector,
                summary=needs_input,
            )

        if needs_approval is not None:
            return self._result(
                STATUS_NEEDS_APPROVAL,
                session_id=first_id,
                final_message=assistant_text,
                collector=collector,
                summary=needs_approval,
            )

        if result_event is None:
            if exit_code != 0:
                return self._result(
                    STATUS_FAILED,
                    session_id=first_id,
                    final_message=assistant_text,
                    collector=collector,
                    error=(
                        "claude exited with status %d before emitting a result event"
                        % exit_code
                    ),
                    error_code="exit_nonzero",
                )
            return self._result(
                STATUS_FAILED,
                session_id=first_id,
                final_message=assistant_text,
                collector=collector,
                error=(
                    "claude stream ended without a result event; completion is never "
                    "inferred from exit status or silence"
                ),
                error_code="incomplete_stream",
            )

        is_error = result_event.get("is_error")
        subtype = result_event.get("subtype")
        terminal_reason = result_event.get("terminal_reason")
        result_text = result_event.get("result")
        if not isinstance(result_text, str) or not result_text.strip():
            result_text = None
        else:
            result_text = result_text.strip()

        if (
            is_error is True
            or (isinstance(subtype, str) and subtype != "success")
            or terminal_reason in {"error", "api_error"}
        ):
            detail = (
                clip(result_text)
                or clip(assistant_error)
                or "Claude reported a failed result (subtype=%r, terminal_reason=%r)"
                % (subtype, terminal_reason)
            )
            return self._result(
                STATUS_FAILED,
                session_id=first_id,
                final_message=result_text or assistant_text,
                collector=collector,
                error=detail,
                error_code="result_error",
            )

        if exit_code != 0:
            return self._result(
                STATUS_FAILED,
                session_id=first_id,
                final_message=result_text or assistant_text,
                collector=collector,
                error="claude exited with status %d after a result event" % exit_code,
                error_code="exit_nonzero",
            )

        if first_id is None:
            return self._result(
                STATUS_FAILED,
                final_message=result_text or assistant_text,
                collector=collector,
                error=(
                    "result arrived without a session_id; no session handle was "
                    "reported, so the run cannot be resumed exactly"
                ),
                error_code="missing_session_id",
            )

        return self._result(
            STATUS_COMPLETED,
            session_id=first_id,
            final_message=result_text or assistant_text,
            collector=collector,
        )


__all__ = ["ClaudeExecutor", "validate_uuid"]
